DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sewaka_app') THEN
    CREATE ROLE sewaka_app
      LOGIN
      PASSWORD 'sewaka_app_dev_only'
      NOSUPERUSER
      NOCREATEDB
      NOCREATEROLE
      NOINHERIT
      NOBYPASSRLS;
  END IF;
END
$$;

ALTER ROLE sewaka_app
  PASSWORD 'sewaka_app_dev_only'
  NOSUPERUSER
  NOCREATEDB
  NOCREATEROLE
  NOINHERIT
  NOBYPASSRLS;

GRANT CONNECT ON DATABASE sewaka TO sewaka_app;
GRANT USAGE ON SCHEMA public TO sewaka_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO sewaka_app;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO sewaka_app;
ALTER DEFAULT PRIVILEGES FOR ROLE sewaka IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO sewaka_app;
ALTER DEFAULT PRIVILEGES FOR ROLE sewaka IN SCHEMA public
  GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO sewaka_app;
